#!/usr/bin/env node
// Authorship guard. Fails when a tracked file or a commit message contains a
// co-author trailer, a generated-by line, an email other than the maintainer's
// noreply address, or the name of a coding assistant outside the files that
// legitimately target that assistant.

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ALLOWED_EMAIL = "5602033+sandeepbazar@users.noreply.github.com";

const TRAILERS = [/co-authored-by/i, /generated with/i, /generated by/i, /authored by ai/i, /ai-assisted/i, /ai assisted/i];
const EMAIL = /(?<![\w+.@-])[A-Za-z0-9][A-Za-z0-9._%+-]*@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}/g;
const EMAIL_ALLOWLIST = new Set([
  ALLOWED_EMAIL,
  "noreply@github.com",
  "example.com",
]);

// Assistant names may appear only where the file targets that assistant.
const ASSISTANTS = /\b(Claude Code|Claude|Codex|Copilot|Gemini|Antigravity|Cursor|Windsurf|Cline|Kiro|OpenClaw|Devin|Qoder|OpenCode|ChatGPT|Anthropic|OpenAI|Bob Shell|IBM Bob)\b/g;
const ASSISTANT_PATHS = [
  /^AGENTS\.md$/, /^GEMINI\.md$/, /^gemini-extension\.json$/, /^commands\//, /^skills\//, /^hooks\//,
  /^\.(claude-plugin|codex-plugin|agents|github\/plugin|devin-plugin|qoder-plugin|qoder|opencode|cursor|windsurf|clinerules|kiro|openclaw|bob)\//,
  /^\.github\/copilot-instructions\.md$/,
  /^mcp\//, // the MCP server names the clients it is configured in, like any other adapter
  /^README(\.[a-z]{2})?\.md$/, /^docs\//, /^action\.yml$/, /^action\//, /^examples\//,
  /^benchmarks\//, /^scripts\//, /^tests\//, /^bin\//, /^package\.json$/, /^CHANGELOG\.md$/, /^CONTRIBUTING\.md$/,
  /^\.github\/workflows\//, /^\.github\/ISSUE_TEMPLATE\//, /^\.github\/PULL_REQUEST_TEMPLATE\.md$/, /^assets\//,
];
const BINARY = /\.(png|gif|jpg|jpeg|ico|woff2?|ttf|zip|tgz)$/i;

function git(...args) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" });
}

const problems = [];

// 1. tracked files
const tracked = git("ls-files", "-z").split("\0").filter(Boolean);
for (const rel of tracked) {
  if (BINARY.test(rel)) continue;
  if (/^benchmarks\/results\/.*\.jsonl$/.test(rel)) continue; // raw model replies are data, not authorship
  if (/^benchmarks\/author\/tasks\//.test(rel)) continue; // task scaffolds and replayed histories are fixtures, not authorship
  let text;
  try {
    text = readFileSync(join(ROOT, rel), "utf8");
  } catch {
    continue;
  }
  const lines = text.split("\n");
  lines.forEach((line, i) => {
    const where = `${rel}:${i + 1}`;
    if (rel !== "scripts/check-attribution.mjs" && rel !== "tests/attribution.test.mjs" && rel !== "LICENSE") {
      for (const t of TRAILERS) if (t.test(line)) problems.push(`${where}: attribution trailer "${line.trim().slice(0, 60)}"`);
    }
    for (const email of line.match(EMAIL) || []) {
      const domain = email.split("@")[1];
      if (!EMAIL_ALLOWLIST.has(email) && !EMAIL_ALLOWLIST.has(domain)) problems.push(`${where}: email ${email}`);
    }
    if (!ASSISTANT_PATHS.some((re) => re.test(rel))) {
      for (const name of line.match(ASSISTANTS) || []) problems.push(`${where}: assistant name "${name}" outside adapter/doc paths`);
    }
  });
}

// 2. commit messages and identities
let log = "";
try {
  log = git("log", "--format=%H%x1f%an%x1f%ae%x1f%cn%x1f%ce%x1f%B%x1e");
} catch {
  log = "";
}
for (const record of log.split("\x1e").filter((r) => r.trim())) {
  const [sha, an, ae, cn, ce, body] = record.trim().split("\x1f");
  const short = sha.slice(0, 7);
  if (ae !== ALLOWED_EMAIL) problems.push(`commit ${short}: author email ${ae}`);
  if (ce !== ALLOWED_EMAIL) problems.push(`commit ${short}: committer email ${ce}`);
  if (an !== "sandeepbazar") problems.push(`commit ${short}: author name ${an}`);
  if (cn !== "sandeepbazar") problems.push(`commit ${short}: committer name ${cn}`);
  for (const t of TRAILERS) if (t.test(body)) problems.push(`commit ${short}: message contains attribution trailer`);
  for (const name of body.match(ASSISTANTS) || []) {
    // assistant names are fine in messages that are about an adapter for that assistant
    if (!/adapter|plugin|extension|hook|install|portab|action|provider|bench|results|skill|rule|doc/i.test(body)) {
      problems.push(`commit ${short}: assistant name "${name}" in message`);
    }
  }
}

if (problems.length) {
  console.error("Attribution check failed:\n  " + problems.join("\n  "));
  process.exit(1);
}
console.log(`attribution clean (${tracked.length} files, ${log.split("\x1e").filter((r) => r.trim()).length} commits)`);
